"""Rebuilds docs/demo: the dashboard running on demo data, for the website.

Needs a database filled with demo data and a built zman-app:

    ZMAN_HOME=./demo cargo run -p zman-core --example seed_demo
    cargo build -p zman-desktop
    ZMAN_HOME=./demo python scripts/demo_site.py 2026-11-19
"""
import io, json, os, shutil, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
UI = os.path.join(ROOT, "crates", "desktop", "ui")
OUT = os.path.join(ROOT, "docs", "demo")
APP = os.path.join(ROOT, "target", "debug", "zman-app.exe" if os.name == "nt" else "zman-app")
day = sys.argv[1]

def dump(lang, period, date):
    env = dict(os.environ, ZMAN_LANG=lang)
    out = subprocess.run([APP, "--dump-dashboard", period, date], capture_output=True, env=env, check=True)
    view = json.loads(out.stdout.decode("utf-8"))
    view["is_current"] = False
    return view

views = {lang: {"day": dump(lang, "day", day), "week": dump(lang, "week", day)} for lang in ("en", "es")}

MOCK = """// Demo data for the website. Generated by scripts/demo_site.py.
(() => {
  const all = %s;
  const asked = new URLSearchParams(location.search).get("lang");
  let lang = asked || ((navigator.language || "").toLowerCase().startsWith("es") ? "es" : "en");
  if (!all[lang]) lang = "en";
  const status = { tracking: "running", error: null, autostart: true, language: lang, db_path: "(demo)", config_path: "(demo)" };
  const connections = {
    claude_desktop: { installed: true, connected: false },
    claude_code_command: 'claude mcp add zman -- "C:/Program Files/zman/zman-app.exe" --mcp',
    sync: null,
  };
  window.zmanMock = async (command, args) => {
    if (command === "get_dashboard") return { ...(all[lang][args.period] || all[lang].day), status };
    if (command === "set_language") { lang = all[args.language] ? args.language : lang; status.language = lang; }
    if (command === "set_autostart") status.autostart = args.enabled;
    if (command === "set_paused") status.tracking = args.paused ? "paused" : "running";
    if (command === "sync_login") connections.sync = { server: args.server, email: args.email, mcp_url: args.server + "/mcp", last_sync_ms: Date.now() };
    if (command === "sync_logout") connections.sync = null;
    if (command === "set_claude_desktop") connections.claude_desktop.connected = args.connected;
    if (command.startsWith("sync_") || command.endsWith("connections") || command === "set_claude_desktop") return connections;
    return status;
  };
})();
"""

os.makedirs(OUT, exist_ok=True)
for name in ("index.html", "style.css", "app.js"):
    shutil.copyfile(os.path.join(UI, name), os.path.join(OUT, name))
with io.open(os.path.join(OUT, "mock.js"), "w", encoding="utf-8", newline="\n") as f:
    f.write(MOCK % json.dumps(views, ensure_ascii=False, separators=(",", ":")))
print("docs/demo rebuilt for", day)

"""Rebuilds the demo data of the dashboard.

Writes `mock.js` (the dashboard's stand-in for the Rust side when it runs in
a plain browser) into the app's UI folder, and rebuilds docs/demo, the copy
of the dashboard shown on the website.

Needs a database filled with demo data and a built zman-app:

    ZMAN_HOME=./demo cargo run -p zman-core --example seed_demo
    cargo build -p zman-desktop
    ZMAN_HOME=./demo python scripts/demo_site.py 2026-11-19
"""
import io, json, os, shutil, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
UI = os.path.join(ROOT, "crates", "desktop", "ui")
OUT = os.path.join(ROOT, "docs", "demo")
APP = os.path.join(ROOT, "target", "debug", "zman-app.exe" if os.name == "nt" else "zman-app")
day = sys.argv[1]

def dump(lang, period, date):
    env = dict(os.environ, ZMAN_LANG=lang)
    out = subprocess.run([APP, "--dump-dashboard", period, date], capture_output=True, env=env, check=True)
    view = json.loads(out.stdout.decode("utf-8"))
    view["is_current"] = False
    return view

views = {lang: {"day": dump(lang, "day", day), "week": dump(lang, "week", day)} for lang in ("en", "es")}

MOCK = """// Demo data, used when the dashboard runs in a browser instead of inside
// the app (and on the website). Generated by scripts/demo_site.py.
(() => {
  const all = %s;
  const asked = new URLSearchParams(location.search).get("lang");
  let lang = asked || ((navigator.language || "").toLowerCase().startsWith("es") ? "es" : "en");
  if (!all[lang]) lang = "en";
  const status = { tracking: "running", error: null, autostart: true, language: lang, db_path: "(demo)", config_path: "(demo)" };
  const connections = {
    claude_desktop: { installed: true, connected: false },
    claude_code_command: 'claude mcp add zman -- "C:/Program Files/zman/zman-app.exe" --mcp',
    sync: null,
  };
  const settings = {
    block: {
      sites: ["x.com"],
      focus_until_ms: 0,
      limits: [{ target: "youtube.com", minutes: 30 }],
      schedules: [{ days: [1, 2, 3, 4, 5], start_min: 540, end_min: 1080 }],
    },
    overrides: [],
    goal_minutes: 300,
    notifications: true,
    assistant_focus: true,
  };
  const settingsReply = () => {
    const view = all[lang].day;
    const score = (name) => (view.categories.find((c) => c.name === name) || { score: 0 }).score;
    return { settings, categories: view.category_order.map((name) => ({ name, score: score(name) })), now_ms: Date.now() };
  };
  const clients = [
    { name: "Acme", own: false, keywords: ["acme"], domains: ["acme.com"], apps: [], payments: [{ date: "2026-11-05", amount: 1200, currency: "USD", note: "" }] },
    { name: "Studio Norte", own: false, keywords: ["norte"], domains: [], apps: ["figma.exe"], payments: [{ date: "2026-11-10", amount: 450000, currency: "ARS", note: "" }] },
    { name: "Side project", own: true, keywords: ["zman"], domains: ["github.com"], apps: [], payments: [] },
  ];
  const H = 3600000;
  const clientsReply = () => {
    const month = { Acme: 31 * H, "Studio Norte": 9.5 * H, "Side project": 6 * H };
    const usage = (ms, c) => {
      const paid = {};
      for (const p of c.payments) paid[p.currency] = (paid[p.currency] || 0) + p.amount;
      const list = Object.entries(paid).map(([currency, amount]) => ({ currency, amount }));
      return { name: c.name, own: c.own, ms, paid: list, per_hour: c.own ? [] : list.map((m) => ({ currency: m.currency, amount: Math.round(m.amount / (ms / H)) })) };
    };
    const known = clients.filter((c) => month[c.name]);
    return {
      clients,
      period: { total_ms: 0, unassigned_ms: 1.2 * H, clients: known.map((c) => ({ ...usage(month[c.name] / 9, c), paid: [], per_hour: [] })) },
      month: { total_ms: 0, unassigned_ms: 14 * H, clients: known.map((c) => usage(month[c.name], c)).sort((a, b) => b.ms - a.ms) },
      month_start: "2026-11-01",
      suggestions: [{ name: "landing-cafe", ms: 2.5 * H }],
    };
  };
  let pairing = null;
  window.zmanMock = async (command, args) => {
    if (command === "get_dashboard") {
      const view = all[lang][args.period] || all[lang].day;
      return { ...view, status, goal_minutes: settings.goal_minutes, focus_until_ms: settings.block.focus_until_ms };
    }
    if (command === "get_clients" || command === "save_clients") {
      if (args.clients) clients.splice(0, clients.length, ...args.clients);
      return clientsReply();
    }
    if (command === "get_settings") return settingsReply();
    if (command === "save_settings") {
      const focus = settings.block.focus_until_ms;
      Object.assign(settings, args.settings);
      settings.block.focus_until_ms = focus;
      return settingsReply();
    }
    if (command === "set_focus") {
      settings.block.focus_until_ms = args.minutes ? Date.now() + args.minutes * 60000 : 0;
      return settingsReply();
    }
    if (command === "set_category") {
      if (!args.category) return null;
      for (const view of Object.values(all[lang])) {
        for (const row of [...view.apps, ...view.sites]) if (row.id === args.name) row.category = args.category;
      }
      return null;
    }
    if (command === "export_csv") return "Downloads/zman-demo.csv";
    if (command === "set_language") { lang = all[args.language] ? args.language : lang; status.language = lang; }
    if (command === "set_autostart") status.autostart = args.enabled;
    if (command === "set_paused") status.tracking = args.paused ? "paused" : "running";
    if (command === "sync_login") connections.sync = { server: args.server, email: args.email, mcp_url: args.server + "/mcp", last_sync_ms: Date.now() };
    if (command === "sync_logout") connections.sync = null;
    // Connecting through the browser: the demo approves itself on the second check.
    if (command === "pair_start") {
      pairing = { server: args.server, checks: 0 };
      return { user_code: "K7QM-2XPA", url: args.server + "/pair?code=K7QM-2XPA", opened: false };
    }
    if (command === "pair_cancel") { pairing = null; return null; }
    if (command === "pair_check") {
      if (!pairing || ++pairing.checks < 2) return null;
      connections.sync = { server: pairing.server, email: "vos@example.com", mcp_url: pairing.server + "/mcp", last_sync_ms: Date.now() };
      pairing = null;
      return connections;
    }
    if (command === "set_claude_desktop") connections.claude_desktop.connected = args.connected;
    if (command.startsWith("sync_") || command.endsWith("connections") || command === "set_claude_desktop") return connections;
    return status;
  };
})();
"""

mock = MOCK % json.dumps(views, ensure_ascii=False, separators=(",", ":"))
os.makedirs(OUT, exist_ok=True)
for folder in (UI, OUT):
    with io.open(os.path.join(folder, "mock.js"), "w", encoding="utf-8", newline="\n") as f:
        f.write(mock)
for name in ("style.css", "app.js"):
    shutil.copyfile(os.path.join(UI, name), os.path.join(OUT, name))
# The demo is part of the home page; search engines should not list it alone.
page = io.open(os.path.join(UI, "index.html"), encoding="utf-8").read()
page = page.replace("<title>", '<meta name="robots" content="noindex">\n  <title>', 1)
with io.open(os.path.join(OUT, "index.html"), "w", encoding="utf-8", newline="\n") as f:
    f.write(page)
print("demo data rebuilt for", day)
